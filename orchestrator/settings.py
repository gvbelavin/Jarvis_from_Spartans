"""
settings.py — настройки оркестратора (модуль А).

ПОЧЕМУ ФАЙЛ НАЗЫВАЕТСЯ settings.py, А НЕ config.py
--------------------------------------------------

Подмодуль аудио (`orchestrator/audio_module`) содержит собственный
`config.py` и импортирует его как top-level модуль (`import config`).
Поэтому `audio_adapter.py` обязан добавить папку `audio_module` в `sys.path`.

Если бы настройки оркестратора лежали в `orchestrator/config.py`, возникла бы
коллизия имён: `import config` резолвился бы в тот файл, который раньше
оказался в `sys.path`. Поведение зависело бы от порядка импортов — это
классический источник трудноуловимых ошибок. Уникальное имя `settings`
убирает проблему полностью: `import config` в любой точке проекта
однозначно означает `config.py` модуля Б.

ВАЖНО ПРО ДУБЛИРОВАНИЕ НАСТРОЕК
-------------------------------

Здесь НЕТ `SPEAKER_THRESHOLD`, `SAMPLE_RATE`, `CHUNK_SIZE` и прочих
параметров аудиомодуля. Единственный источник правды по ним — `config.py`
модуля Б; адаптер читает их оттуда (`_speaker_threshold()` в
`audio_adapter.py`). Копия значения здесь разошлась бы с оригиналом при
первой же правке чужого модуля.
"""

from __future__ import annotations

from pathlib import Path

# Корень папки orchestrator/
BASE_DIR = Path(__file__).resolve().parent

# Папка git submodule с аудиомодулем (модуль Б).
# Модули Б используют «плоские» импорты (`import config`), поэтому эта
# папка добавляется в sys.path — см. audio_adapter.py.
AUDIO_MODULE_DIR = BASE_DIR / "audio_module"

# Папка git submodule с модулем памяти (модуль Ц).
# Внутри лежит пакет jarvis_memory, который импортируется как top-level.
MEMORY_MODULE_DIR = BASE_DIR / "memory_module"

# Сколько максимум ждать записи команды после wake word.
# Модуль Б завершает запись только по тишине и собственного таймаута
# не имеет: если после wake word никто ничего не скажет, запись не
# закончится никогда. Это страховка оркестратора, а не настройка модуля Б.
DEFAULT_RECORD_TIMEOUT = 10.0

# Модуль индикации (модуль 5, Степан): ESP32 на USB-serial.
# Плата отображает состояния оркестратора на LED и шлёт события кнопки BOOT
# (mute toggle) обратно в оркестратор. Если платы нет — при открытии порта
# индикатор молча деградирует до заглушки, пайплайн продолжает работать.
INDICATOR_PORT = "/dev/ttyUSB0"
